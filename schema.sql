CREATE TABLE IF NOT EXISTS coches(
 id TEXT PRIMARY KEY,
 marca TEXT NOT NULL, modelo TEXT NOT NULL,
 anio INTEGER NOT NULL, km INTEGER NOT NULL, precio INTEGER NOT NULL,
 comb TEXT NOT NULL, cambio TEXT NOT NULL, tipo TEXT NOT NULL,
 dgt TEXT NOT NULL DEFAULT '', potencia INTEGER, color TEXT NOT NULL DEFAULT '', propietarios INTEGER,
 descr TEXT NOT NULL DEFAULT '',
 estado TEXT NOT NULL DEFAULT 'disponible',
 destacado INTEGER NOT NULL DEFAULT 0,
 v INTEGER NOT NULL DEFAULT 0,
 creado INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS fotos(
 car TEXT NOT NULL, pos INTEGER NOT NULL, mime TEXT NOT NULL, data TEXT NOT NULL,
 PRIMARY KEY(car,pos)
);